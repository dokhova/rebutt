// POST /api/insights  { context } → { tip_title, tip_text, noticed }
// «Совет на сегодня» на главной и блок «ИИ заметил» в инсайтах. Клиент кэширует ответ на день.
import { chatJSON, handler, SAFETY, ctxText } from './_lib/openai.js';

export const config = { maxDuration: 60 };

const schema = {
  type: 'object',
  additionalProperties: false,
  required: ['tip_title', 'tip_text', 'tips', 'noticed'],
  properties: {
    tip_title: { type: 'string', description: 'Сам совет одной строкой — конкретное действие на сегодня, до 40 символов. Например: «Ещё 2 стакана воды до вечера», «Овощи к ужину». Не общие слова вроде «План на сегодня» или «Совет дня»' },
    tip_text: { type: 'string', description: 'Конкретный совет на сегодня, одно предложение, до 120 символов' },
    tips: {
      type: 'array', minItems: 1, maxItems: 2,
      description: 'Два разных персональных совета на сегодня для главного экрана. Каждый — одна строка до 45 символов, с конкретикой ИМЕННО этого человека: его цифры (вода, клетчатка к его ориентиру, тип стула, сколько дней), названия его блюд, его цели или фаза цикла. Например: «После гречки стул ровнее — повтори на обед», «Вода 1,1 из 2 л вчера — стакан с утра». Не общие советы, которые подошли бы любому',
      items: { type: 'string' }
    },
    noticed: { type: 'string', description: 'Одна закономерность из данных (еда ↔ стул/симптомы, регулярность, цикл) — одно короткое предложение, до 100 символов, с цифрой или названием блюда. Например: «После пиццы вечером — 62%, в дни с овсянкой — от 80%». Если данных мало — одним предложением, что записывать' }
  }
};

export default handler(async (body) => {
  return chatJSON({
    schemaName: 'insights',
    schema,
    system: SAFETY + ' По профилю и записям пользователя дай один практичный совет на сегодня и одно наблюдение-закономерность. Конкретика из данных (названия блюд, типы стула, дни, сколько воды и клетчатки относительно личного ориентира daily_targets) лучше общих слов. Совет должен работать на цели пользователя (goals, own_goal) и учитывать фазу цикла, если она есть. Для наблюдения используй и сводку за всё время (summary), а не только последние дни. Советы tips — оба персональные, из данных пользователя, и не повторяют друг друга. Заголовок совета (tip_title) — это сама рекомендация, конкретное действие, а не название вроде «план» или «совет»; спокойно, без тревоги.',
    user: 'Данные пользователя (JSON): ' + ctxText(body.context)
  });
});

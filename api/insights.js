// POST /api/insights  { context } → { tip_title, tip_text, noticed }
// «Совет на сегодня» на главной и блок «ИИ заметил» в инсайтах. Клиент кэширует ответ на день.
import { chatJSON, handler, SAFETY, ctxText } from './_lib/openai.js';

export const config = { maxDuration: 60 };

const schema = {
  type: 'object',
  additionalProperties: false,
  required: ['tip_title', 'tip_text', 'tips', 'noticed'],
  properties: {
    tip_title: { type: 'string', description: 'Сам совет — короткая простая фраза, конкретное действие на сегодня, до 35 символов, без цифр. Например: «Стакан воды до обеда», «Овощи к ужину». Не общие слова вроде «План на сегодня» или «Совет дня»' },
    tip_text: { type: 'string', description: 'Конкретный совет на сегодня, одно предложение, до 120 символов' },
    tips: {
      type: 'array', minItems: 1, maxItems: 2,
      description: 'Два разных совета на сегодня для главного экрана. Каждый — одна короткая фраза до 35 символов, простыми бытовыми словами, как сказала бы подруга. БЕЗ цифр, граммов, процентов, литров, стрелок, скобок, слэшей и двоеточий, без терминов (не «дефекация», не «клетчатка», не «цельнозерновые» — «овощи», «каша», «фрукты», «вода»). Одно действие, без пояснений, зачем оно. Подбирай по данным человека: его блюда, цели, фаза цикла — но без расчётов. Например: «Яблоко на перекус», «Стакан воды с утра», «Гречка на обед, как во вторник», «Овощи к ужину». Не пиши общие слова вроде «Следи за питанием»',
      items: { type: 'string' }
    },
    noticed: { type: 'string', description: 'Одна закономерность из данных (еда ↔ стул/симптомы, регулярность, цикл) — одно короткое предложение, до 90 символов, простыми словами, без граммов и расчётов (можно назвать блюдо или день). Например: «В дни с овсянкой комфорт выше, чем после пиццы вечером». Если данных мало — одним предложением, что записывать' }
  }
};

/** Страховка: совет на главной — короткая фраза без расчётов. Длинный или с граммами/процентами/стрелками — отбрасываем,
 *  тогда на главной покажутся простые советы из domain/suggestions.js. */
const MAX_TIP = 48;
export function shortTip(t) {
  const s = String(t || '').trim().replace(/[.;,:]+$/, '');
  return s && s.length <= MAX_TIP && !/\d\s*(г|мл|л|%)|[→/½]|\+\d/.test(s) ? s : '';
}

export default handler(async (body) => {
  const r = await chatJSON({
    schemaName: 'insights',
    schema,
    system: SAFETY + ' По профилю и записям пользователя дай один практичный совет на сегодня и одно наблюдение-закономерность. Опирайся на данные (блюда, дни, сколько было воды и клетчатки относительно daily_targets), но пиши легко и просто: это не урок математики — никаких цифр и граммов в советах, только понятное действие. Совет должен работать на цели пользователя (goals, own_goal) и учитывать фазу цикла, если она есть. Для наблюдения используй и сводку за всё время (summary), а не только последние дни. Советы tips — оба персональные, из данных пользователя, и не повторяют друг друга. Заголовок совета (tip_title) — это сама рекомендация, конкретное действие, а не название вроде «план» или «совет»; спокойно, без тревоги.',
    user: 'Данные пользователя (JSON): ' + ctxText(body.context)
  });
  if (r && Array.isArray(r.tips)) r.tips = r.tips.map(shortTip).filter(Boolean);
  if (r && r.tip_title) r.tip_title = shortTip(r.tip_title);
  return r;
});
